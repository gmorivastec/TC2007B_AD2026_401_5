package mx.tec.nativeexploration

import android.os.Bundle
import android.widget.Button
import android.widget.EditText
import androidx.activity.enableEdgeToEdge
import androidx.appcompat.app.AppCompatActivity
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat

// in native development an app's logic is divided in
// units called Activities
// traditionally divided in a logic file and a separate XML GUI file
// later unified using compose

// for GUI we have a WYSIWYG editor
// old school java - uses layouts for GUI

class MainActivity : AppCompatActivity() {

    //References to GUI elements
    private lateinit var textInput : EditText
    private lateinit var button1 : Button
    private lateinit var button2 : Button

    // activities have a lifecycle
    // https://developer.android.com/guide/components/activities/activity-lifecycle
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        // there is no implicit relationship between a layout file and a code file
        // the relationship must be made explicit like this vvvvvv

        // R - resource index generated by development tools
        // anything on the res folder can be accessed through R
        setContentView(R.layout.activity_main)
        ViewCompat.setOnApplyWindowInsetsListener(findViewById(R.id.main)) { v, insets ->
            val systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom)
            insets
        }

        // there are several strategies to deal with UI from code in views
        // we are going to use the most basic one

        // how to get a reference to a widget on the RUNNING activity
        // (can be null if widget is not found, so beware!)

        // findviewbyid MIGHT fail
        // reason: it has no compilation-time verification for the existence of a widget
        textInput = findViewById(R.id.editText)
        button1 = findViewById(R.id.button)
        button2 = findViewById(R.id.button2)

        button1.text = "SAY HELLO"
        button2.text = "GO TO COMPOSE ACTIVITY"

        // 2 ways to subscribe logic to a GUI event
        // 1 - programmatically through code
        // 2 - establishing a relationship through GUI with a function
    }
}